"""
Abstract protocols and DTOs for external infrastructure adapters.

Architectural Invariants:
- All interfaces must be @runtime_checkable typing.Protocol definitions.
- ZERO SQL, ORM, or database imports.
- ZERO HTTP clients (httpx, requests) or subprocess calls.
- Pure Pydantic v2 DTOs for structured data exchange.
"""
from __future__ import annotations

from typing import Any, AsyncIterator, Protocol, runtime_checkable
from pydantic import BaseModel, ConfigDict, Field


# =============================================================================
# Jev Decision Client Protocol (Tier 1 Calibrated Classifier)
# =============================================================================

class JevEvaluationResultDTO(BaseModel):
    """Result of evaluating calibrated probability questions against item state."""
    model_config = ConfigDict(frozen=True)

    answers: dict[str, str] = Field(
        ...,
        description="Categorical or boolean answers to evaluated questions",
    )
    probabilities: dict[str, float] = Field(
        ...,
        description="Calibrated probability scores in [0.0, 1.0] for each question",
    )
    model_version: str = Field(
        default="jev-classifier-v1",
        description="Version string of the Jev model used for evaluation",
    )


@runtime_checkable
class JevClientProtocol(Protocol):
    """Abstract contract for TypeSafe AI Jev Decision API integration."""

    async def evaluate(
        self,
        state: dict[str, Any],
        questions: dict[str, str],
        model: str | None = None,
    ) -> JevEvaluationResultDTO:
        """
        Evaluate a set of calibrated probability questions against an input state dictionary.

        Args:
            state: Dictionary containing item properties (e.g. sender, subject, body).
            questions: Dictionary mapping question keys to calibrated prompt instructions.
            model: Optional model override. Defaults to configured JEV_MODEL.

        Returns:
            JevEvaluationResultDTO containing categorical answers and float probabilities.
        """
        ...

    async def evaluate_batch(
        self,
        states: list[dict[str, Any]],
        questions: dict[str, str],
        model: str | None = None,
    ) -> list[JevEvaluationResultDTO]:
        """
        Batch evaluate multiple state items against a common question set.

        Args:
            states: List of state dictionaries.
            questions: Dictionary mapping question keys to calibrated prompt instructions.
            model: Optional model override.

        Returns:
            List of JevEvaluationResultDTO instances corresponding to the input states.
        """
        ...

    async def is_healthy(self) -> bool:
        """Check whether the Jev API service is reachable and healthy."""
        ...


# =============================================================================
# LLM Multi-Provider Protocol (Tier 2 Fast + Tier 3 Reasoning + Embeddings)
# =============================================================================

class LLMToolCallDTO(BaseModel):
    """Tool invocation emitted by the language model."""
    model_config = ConfigDict(frozen=True)

    id: str = Field(..., description="Unique tool call identifier generated by the LLM")
    name: str = Field(..., description="Name of the tool requested")
    arguments: dict[str, Any] = Field(
        default_factory=dict,
        description="Parsed JSON arguments supplied to the tool",
    )


class LLMResponseDTO(BaseModel):
    """Complete response from an LLM inference call."""
    model_config = ConfigDict(frozen=True)

    content: str | None = Field(None, description="Assistant message text content")
    tool_calls: list[LLMToolCallDTO] = Field(
        default_factory=list,
        description="Parallel tool calls emitted by the model",
    )
    prompt_tokens: int = Field(0, description="Tokens consumed in prompt")
    completion_tokens: int = Field(0, description="Tokens generated in completion")
    total_tokens: int = Field(0, description="Total tokens consumed")
    finish_reason: str = Field(
        "stop",
        description="Reason completion finished: stop, tool_calls, length, etc.",
    )
    model: str = Field("", description="Actual model identifier used for inference")


class LLMStreamChunkDTO(BaseModel):
    """Incremental chunk emitted during streaming LLM inference."""
    model_config = ConfigDict(frozen=True)

    delta_content: str | None = Field(None, description="Delta text token")
    tool_call_chunks: list[dict[str, Any]] | None = Field(
        None,
        description="Incremental tool call fragments",
    )
    done: bool = Field(False, description="True if stream has concluded")
    finish_reason: str | None = Field(None, description="Stream termination reason")


@runtime_checkable
class LLMClientProtocol(Protocol):
    """Abstract contract for OpenAI-compatible multi-tier LLM inference and embeddings."""

    async def complete(
        self,
        messages: list[dict[str, Any]],
        tools: list[dict[str, Any]] | None = None,
        temperature: float = 0.7,
        tier: str = "reasoning",
        max_tokens: int | None = None,
    ) -> LLMResponseDTO:
        """
        Execute chat completion against specified model tier ('fast' or 'reasoning').

        Args:
            messages: OpenAI-format list of message dicts (role, content, tool_calls, etc.).
            tools: Optional OpenAI tool definitions schema list.
            temperature: Sampling temperature.
            tier: 'fast' (Tier 2, e.g. gpt-4o-mini) or 'reasoning' (Tier 3, e.g. gpt-4o).
            max_tokens: Optional token generation cap.

        Returns:
            LLMResponseDTO containing text content, tool calls, and token usage.
        """
        ...

    async def stream_complete(
        self,
        messages: list[dict[str, Any]],
        tools: list[dict[str, Any]] | None = None,
        temperature: float = 0.7,
        tier: str = "reasoning",
        max_tokens: int | None = None,
    ) -> AsyncIterator[LLMStreamChunkDTO]:
        """
        Stream assistant tokens and tool calls incrementally.

        Args:
            messages: OpenAI-format list of message dicts.
            tools: Optional OpenAI tool definitions schema list.
            temperature: Sampling temperature.
            tier: 'fast' or 'reasoning'.
            max_tokens: Optional token generation cap.

        Yields:
            LLMStreamChunkDTO with token deltas and tool call fragments.
        """
        ...

    async def embed_texts(
        self,
        texts: list[str],
        model: str | None = None,
    ) -> list[list[float]]:
        """
        Generate dense vector embeddings for input text chunks.

        Args:
            texts: List of strings to embed.
            model: Optional embedding model override. Defaults to EMBEDDING_MODEL.

        Returns:
            List of 1536-dimensional float vector embeddings.
        """
        ...

    async def is_healthy(self) -> bool:
        """Check whether the upstream LLM providers are reachable."""
        ...


