# Docker Sandbox Runner Protocol (Subsystem 6: Sandbox & Workspace Lifecycle)
# =============================================================================

class SandboxExecResultDTO(BaseModel):
    """Execution output from a command run inside an isolated sandbox."""
    model_config = ConfigDict(frozen=True)

    exit_code: int = Field(..., description="Process exit code (0 = success)")
    stdout: str = Field(..., description="Standard output text")
    stderr: str = Field(..., description="Standard error text")
    duration_ms: float = Field(..., description="Command execution duration in milliseconds")


class SandboxContainerDTO(BaseModel):
    """Metadata describing an active or created sandbox container."""
    model_config = ConfigDict(frozen=True)

    container_id: str = Field(..., description="Docker container identifier or hash")
    workspace_path: str = Field(..., description="Host mount or internal workspace path")
    created_at: float = Field(..., description="POSIX timestamp of container creation")


@runtime_checkable
class SandboxRunnerProtocol(Protocol):
    """Abstract contract for Docker sandbox container management and workspace snapshotting."""

    async def create_container(
        self,
        run_id: str,
        timeout_seconds: int = 900,
    ) -> SandboxContainerDTO:
        """
        Create an isolated container with read-only root and writable tmpfs /workspace.

        Args:
            run_id: Unique execution run ID.
            timeout_seconds: Hard execution timeout for container lifespan.

        Returns:
            SandboxContainerDTO containing container ID and workspace location.
        """
        ...

    async def execute_command(
        self,
        container_id: str,
        command: str,
        timeout_seconds: int = 60,
    ) -> SandboxExecResultDTO:
        """
        Execute a bash command inside the sandbox container.

        Args:
            container_id: Target container identifier.
            command: Shell command string.
            timeout_seconds: Execution timeout.

        Returns:
            SandboxExecResultDTO with exit code, stdout, and stderr.
        """
        ...

    async def read_file(self, container_id: str, path: str) -> bytes:
        """
        Read binary content of a file from container /workspace.

        Args:
            container_id: Target container identifier.
            path: Relative or absolute path inside /workspace.

        Returns:
            Raw file bytes.
        """
        ...

    async def write_file(self, container_id: str, path: str, content: bytes) -> None:
        """
        Write binary content to a file inside container /workspace.

        Args:
            container_id: Target container identifier.
            path: Relative or absolute path inside /workspace.
            content: Raw file bytes to write.
        """
        ...

    async def snapshot_workspace(self, container_id: str, target_tar_path: str) -> int:
        """
        Archive /workspace to a host tarball on run pause.

        Args:
            container_id: Container whose workspace will be captured.
            target_tar_path: Host filesystem path for output tar archive.

        Returns:
            Byte size of created tar archive.
        """
        ...

    async def restore_workspace(self, container_id: str, source_tar_path: str) -> None:
        """
        Extract a host tarball into container /workspace upon run resumption.

        Args:
            container_id: Target container to receive files.
            source_tar_path: Host filesystem path to source tar archive.
        """
        ...

    async def stop_and_remove(self, container_id: str) -> None:
        """
        Terminate and cleanly delete container to release resources.

        Args:
            container_id: Container identifier to reap.
        """
        ...

    async def is_healthy(self) -> bool:
        """Check whether the Docker daemon or docker-socket-proxy is reachable."""
        ...


