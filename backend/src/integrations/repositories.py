# Push Notification Dispatcher Protocol
# =============================================================================

class NotificationPayloadDTO(BaseModel):
    """Structured push notification payload for the mobile companion app."""
    model_config = ConfigDict(frozen=True)

    target: str = Field(..., description="Target topic, channel, or device push token")
    title: str = Field(..., description="Notification title")
    body: str = Field(..., description="Notification body content")
    data: dict[str, Any] | None = Field(
        None,
        description="Optional custom key-value metadata payload",
    )
    click_action: str | None = Field(
        None,
        description="Deep link URI or action to trigger upon notification tap",
    )


class NotificationResultDTO(BaseModel):
    """Outcome of a push notification dispatch attempt."""
    model_config = ConfigDict(frozen=True)

    success: bool = Field(..., description="True if successfully accepted by push gateway")
    message_id: str | None = Field(None, description="External message ID from gateway")
    error: str | None = Field(None, description="Error explanation if delivery failed")


@runtime_checkable
class NotificationDispatcherProtocol(Protocol):
    """Abstract contract for dispatching push notifications to companion devices."""

    async def send_push_notification(
        self,
        target: str,
        title: str,
        body: str,
        data: dict[str, Any] | None = None,
    ) -> bool:
        """
        Dispatch a push notification to a specified mobile target.

        Args:
            target: Device push token or ntfy topic.
            title: Headline string.
            body: Body text.
            data: Optional metadata dictionary.

        Returns:
            True if delivered to notification gateway successfully.
        """
        ...

    async def dispatch(self, payload: NotificationPayloadDTO) -> NotificationResultDTO:
        """
        Dispatch a structured NotificationPayloadDTO.

        Args:
            payload: NotificationPayloadDTO instance.

        Returns:
            NotificationResultDTO with delivery status.
        """
        ...

    async def is_healthy(self) -> bool:
        """Check whether push notification service/gateway is reachable."""
        ...
