# Model Context Protocol (MCP) Host Protocol (Subsystem 7: Connectors Engine)
# =============================================================================

class MCPToolDefinitionDTO(BaseModel):
    """Schema definition for an external tool exposed by an MCP connector."""
    model_config = ConfigDict(frozen=True)

    name: str = Field(..., description="Tool function name (e.g. gmail_send)")
    description: str = Field(..., description="Natural language description of tool behavior")
    input_schema: dict[str, Any] = Field(
        default_factory=dict,
        description="JSON Schema for tool input arguments",
    )
    approval_level: str = Field(
        "read",
        description="Security classification: 'read' (auto) or 'external' (human approval)",
    )


class MCPToolResultDTO(BaseModel):
    """Output result from invoking an MCP connector tool."""
    model_config = ConfigDict(frozen=True)

    tool_call_id: str = Field(..., description="Associated LLM tool call identifier")
    output: str | dict[str, Any] = Field(
        ...,
        description="Tool execution output text or structured dictionary",
    )
    is_error: bool = Field(False, description="True if tool execution failed")


@runtime_checkable
class MCPHostProtocol(Protocol):
    """Abstract contract for managing Model Context Protocol client connections and tools."""

    async def list_tools(self, connector_id: str) -> list[MCPToolDefinitionDTO]:
        """
        Discover tools advertised by an active connector.

        Args:
            connector_id: Identifier of the connector account or service.

        Returns:
            List of MCPToolDefinitionDTO objects.
        """
        ...

    async def execute_tool(
        self,
        connector_id: str,
        tool_name: str,
        arguments: dict[str, Any],
        tool_call_id: str = "",
    ) -> MCPToolResultDTO:
        """
        Invoke a tool on an MCP connector server.

        Args:
            connector_id: Identifier of the target connector.
            tool_name: Name of tool to execute.
            arguments: Keyword arguments matching the tool's input schema.
            tool_call_id: Correlation ID matching the assistant's tool call.

        Returns:
            MCPToolResultDTO containing execution output and status.
        """
        ...

    async def get_tool_approval_policy(
        self,
        connector_id: str,
        tool_name: str,
    ) -> str:
        """
        Query security approval policy for tool: 'read' (auto) or 'external' (ask).

        Args:
            connector_id: Identifier of the connector.
            tool_name: Tool name.

        Returns:
            Approval policy string: 'read' or 'external'.
        """
        ...

    async def is_healthy(self, connector_id: str) -> bool:
        """Check whether the connector transport is alive and responding."""
        ...


