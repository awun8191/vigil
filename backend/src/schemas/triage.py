"""Triage and action cards schemas."""
from __future__ import annotations

from datetime import datetime, timezone
from typing import TYPE_CHECKING, Any
import uuid

import sqlalchemy as sa
from sqlalchemy import (
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship
from src.schemas.base import Base

if TYPE_CHECKING:
    from src.schemas.connectors import ConnectorItemModel
    from src.schemas.identity import UserModel
    from src.schemas.runtime import RunModel


class TriageDecisionModel(Base):
    """Classification record generated by the triage pipeline for an ingested item."""

    __tablename__ = "triage_decisions"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    item_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("connector_items.id", ondelete="CASCADE"),
        nullable=False,
    )
    answers: Mapped[dict[str, str]] = mapped_column(
        JSONB,
        nullable=False,
        default=dict,
        server_default=sa.text("'{}'::jsonb"),
    )
    probabilities: Mapped[dict[str, float]] = mapped_column(
        JSONB,
        nullable=False,
        default=dict,
        server_default=sa.text("'{}'::jsonb"),
    )
    decision: Mapped[str] = mapped_column(String(64), nullable=False, index=True)
    model_version: Mapped[str] = mapped_column(String(64), nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        server_default=func.now(),
    )

    __table_args__ = (
        # A re-triage stores a second verdict for a new model version.
        UniqueConstraint("item_id", "model_version", name="uq_triage_decisions_item_model"),
        Index("ix_triage_decisions_item_id", "item_id"),
    )

    item: Mapped[ConnectorItemModel] = relationship(
        "ConnectorItemModel", back_populates="triage_decision"
    )


class CardModel(Base):
    """Proactive action card surfaced in the user feed."""

    __tablename__ = "cards"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    item_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("connector_items.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    thread_id: Mapped[str | None] = mapped_column(
        String(255), nullable=True, index=True
    )
    type: Mapped[str] = mapped_column(String(64), nullable=False, index=True)
    urgency: Mapped[str] = mapped_column(String(32), nullable=False, index=True)
    proactivity_tag: Mapped[str | None] = mapped_column(
        String(64), nullable=True, index=True
    )
    verb: Mapped[str | None] = mapped_column(String(64), nullable=True)
    title: Mapped[str] = mapped_column(String(500), nullable=False)
    summary: Mapped[str | None] = mapped_column(Text, nullable=True)
    due_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True, index=True
    )
    status: Mapped[str] = mapped_column(
        String(32),
        nullable=False,
        default="new",
        server_default=sa.text("'new'"),
        index=True,
    )
    feedback: Mapped[str | None] = mapped_column(String(32), nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        server_default=func.now(),
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
        server_default=func.now(),
    )

    __table_args__ = (
        Index("ix_cards_user_status_urgency", "user_id", "status", "urgency"),
        Index("ix_cards_user_due_at", "user_id", "due_at"),
    )

    user: Mapped[UserModel] = relationship("UserModel", back_populates="cards")
    item: Mapped[ConnectorItemModel | None] = relationship(
        "ConnectorItemModel", back_populates="cards"
    )
    actions: Mapped[list[CardActionModel]] = relationship(
        "CardActionModel",
        back_populates="card",
        cascade="all, delete-orphan",
        order_by="CardActionModel.sequence",
        lazy="selectin",
    )
    runs: Mapped[list[RunModel]] = relationship("RunModel", back_populates="card")


class CardActionModel(Base):
    """Action button attached to an action card."""

    __tablename__ = "card_actions"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    card_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("cards.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    action_key: Mapped[str] = mapped_column(String(64), nullable=False)
    label: Mapped[str] = mapped_column(String(255), nullable=False)
    action_type: Mapped[str] = mapped_column(String(64), nullable=False)
    verb: Mapped[str | None] = mapped_column(String(64), nullable=True)
    payload: Mapped[dict[str, Any]] = mapped_column(
        JSONB,
        nullable=False,
        default=dict,
        server_default=sa.text("'{}'::jsonb"),
    )
    sequence: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        server_default=sa.text("0"),
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        server_default=func.now(),
    )

    __table_args__ = (
        UniqueConstraint("card_id", "action_key", name="uq_card_actions_card_key"),
    )

    card: Mapped[CardModel] = relationship("CardModel", back_populates="actions")
